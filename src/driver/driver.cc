namespace ember {

namespace {

void finish(CompileOutput& out) {
    out.error_count = out.diags.error_count();
    out.diagnostics = out.diags.render(*out.source);
    out.ok = !out.diags.has_errors();
}

void internal(CompileOutput& out, const std::string& what) {
    out.ok = false;
    out.internal_error = true;
    out.diagnostics += "internal compiler error: " + what +
                       "\n  = note: this is a bug in the Ember compiler, not in your program\n";
}

}  // namespace

std::unique_ptr<CompileOutput> compile(const std::string& name, const std::string& text, const CompileOptions& opts,
                                       Stage stop_after) {
    auto out = std::make_unique<CompileOutput>();
    if (text.size() > opts.max_source_bytes) {
        out->source = std::make_unique<SourceFile>(name, "");
        out->diags.error(DiagKind::Limit, Span{},
                         "source file is too large (" + std::to_string(text.size()) + " bytes, limit " +
                             std::to_string(opts.max_source_bytes) + ")");
        finish(*out);
        return out;
    }
    out->source = std::make_unique<SourceFile>(name, text);
    try {
        Lexer lexer(*out->source, out->diags);
        auto tokens = lexer.tokenize();
        Parser parser(std::move(tokens), out->diags);
        out->program = parser.parse_program();
        if (out->diags.has_errors() || stop_after == Stage::Parse) {
            finish(*out);
            return out;
        }
        Resolver resolver(out->program, out->sema, out->diags);
        resolver.run();
        if (!out->diags.has_errors()) {
            TypeChecker checker(out->program, out->sema, out->diags);
            checker.run();
        }
        if (out->diags.has_errors() || stop_after == Stage::Check) {
            finish(*out);
            return out;
        }
        ir::LowerOptions lo;
        lo.rotate_loops = opts.opt_level >= 1 && opts.rotate_loops;
        out->ir = ir::lower_program(out->program, out->sema, lo);
        if (opts.validate_ir) {
            auto errs = ir::validate(out->ir);
            if (!errs.empty()) {
                finish(*out);
                internal(*out, "invalid IR after lowering: " + errs[0]);
                return out;
            }
        }
        out->opt_stats = ir::optimize(out->ir, opts.opt_level);
        if (opts.validate_ir) {
            auto errs = ir::validate(out->ir);
            if (!errs.empty()) {
                finish(*out);
                internal(*out, "invalid IR after optimization: " + errs[0]);
                return out;
            }
        }
        if (stop_after == Stage::IR) {
            finish(*out);
            return out;
        }
        try {
            codegen::CodegenOptions cg;
            cg.block_layout = opts.opt_level >= 1 && opts.block_layout;
            cg.superinstructions = opts.opt_level >= 1 && opts.superinstructions;
            out->bytecode = codegen::generate(out->ir, name, cg);
        } catch (const codegen::LimitError& e) {
            out->diags.error(DiagKind::Limit, Span{}, e.what());
            finish(*out);
            return out;
        }
        out->bytecode.has_debug_info = opts.debug_info;
        auto vr = bc::verify(out->bytecode);
        finish(*out);
        if (!vr.ok()) internal(*out, "generated bytecode failed verification: " + vr.errors[0]);
    } catch (const std::bad_alloc&) {
        out->diags.error(DiagKind::Limit, Span{}, "out of memory while compiling");
        finish(*out);
    } catch (const std::exception& e) {
        finish(*out);
        internal(*out, e.what());
    }
    return out;
}

}  // namespace ember
